"""Forms by which a module under shuttle/ might reach what it must not, with the verdict.

A row is a tuple: (label, source, folder, caught_by, note).

- label: what the form attacks.
- source: the module's text.
- folder: where the module sits under shuttle/ ("core", "core/drivers", "shell", ...). A
  folder whose last part starts with "noinit" is made without an __init__.py (the linter then
  has no package to resolve a relative import against). A folder ending in ".py" is the
  module's own place , for the forms that depend on being an __init__.
- caught_by: who must refuse it. "both": the rule test (tests/by_value/test_rules.py,
  check_module) and the linter's banned-import rule (TID251). "rule test": the rule test alone
  (the linter says nothing about it). "lint": the linter alone (check_module returns no
  problem). None: the form is allowed and neither says anything.
- note: why, when it is not obvious; "known gap" marks a form that gets through both guards
  although it should not (the verdict then is None and the reason is written here).

The verdict "refused" is any caught_by that is not None. Rows are grouped by what they reach.
"""

